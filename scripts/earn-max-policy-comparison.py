#!/usr/bin/env python3
"""Offline sensitivity tables from retained Earn MAX evidence; no RPC or secrets."""
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs/evidence/earn-max-policy-2026-11-04.json"


def buffer_case(data, target):
    baseline = data["baseline_buffer_usdc"]
    low = high = 0.0
    for episode in data["episodes"]:
        reserve = min(target(episode["prior_day_nav_micros"] / 1e6), episode["prior_day_nav_micros"] / 1e6)
        avoided_funding = min(max(reserve - baseline, 0), episode["funding_restored_micros"] / 1e6)
        # An equity withdrawal sells its share of collateral AND repays debt.
        turnover = avoided_funding * episode["leverage_assumption"]
        low += turnover * data["exit_bps_low"] / 10000
        high += turnover * data["exit_bps_high"] / 10000
    extras = [max(min(target(nav / 1e6), nav / 1e6) - baseline, 0) for nav in data["daily_nav_micros"].values()]
    assert len(extras) == data["window_days"]
    # Charge the full reserve every day: conservative when it is being spent.
    drag_low = sum(extras) * math.expm1(math.log1p(data["carry_apy_low"]) / 365.25)
    drag_high = sum(extras) * math.expm1(math.log1p(data["carry_apy_high"]) / 365.25)
    return low, high, drag_low, drag_high


def round_trip(equity, level, native, borrow, days, cost_bps):
    years = days / 365.25
    income = equity * level * math.expm1(math.log1p(native) * years)
    interest = equity * (level - 1) * math.expm1(math.log1p(borrow) * years)
    cost = equity * level * cost_bps / 10000
    return income - interest - cost


def amm_sale(amount, chunks, replenish):
    # A deliberately simple constant-product pool, with no fees and a $1 mark.
    x = y = 1_000_000.0
    received = 0.0
    for _ in range(chunks):
        part = amount / chunks
        if replenish:
            x = y = 1_000_000.0
        out = y - x * y / (x + part)
        received += out
        x, y = x + part, y - out
    return amount - received


def main():
    data = json.loads(DATA.read_text())
    assert len(data["episodes"]) == 2
    assert buffer_case(data, lambda _: 5000) == (0, 0, 0, 0)
    bounded_reserve = lambda nav: min(25000, max(5000, nav * .10))
    assert bounded_reserve(40000) == 5000 and bounded_reserve(175000) == 17500
    assert buffer_case(data, bounded_reserve) == buffer_case(data, lambda _: 25000)
    assert math.isclose(amm_sale(5000, 1, False), amm_sale(5000, 10, False), abs_tol=1e-8)
    assert amm_sale(5000, 10, True) < amm_sale(5000, 1, False)
    assert round_trip(1000, 1, .10, .80, 3, 0) == round_trip(1000, 1, .10, .01, 3, 0)

    print("# Earn MAX policy sensitivity — captured November 4, 2026\n")
    print("Generated by `python3 scripts/earn-max-policy-comparison.py`. This is a bounded scenario model, not a reconstructed alternative chain history.\n")
    print("## Cash reserve\n")
    print("Compares a hypothetically fully funded $5,000 reserve with larger reserves over October 23–November 4. Assumes the extra cash was available before **both** withdrawal episodes, replenished from incoming cash between them, and not obtained by an extra forced sale. October 25 predates the actual $5,000 policy.\n")
    print("Costs use 20–65 bps per collateral sale and 2.5x / 1.5x leverage for the two episodes. Foregone yield uses 10.19–16.31% APY. Quotes, rate feedback and actual flow-by-flow reserve availability are unavailable. The savings range below is conditional, not a guaranteed lower bound; without prefunding, savings can be zero.\n")
    print("| Reserve | Conditional sale-cost savings | Yield forgone, 12 days | Conditional net change |")
    print("|---|---:|---:|---:|")
    cases = [(f"${n:,}", lambda _, n=n: n) for n in (5000, 10000, 25000, 50000)]
    cases += [(f"{n}% of NAV, $5k floor", lambda nav, n=n: max(5000, nav * n / 100)) for n in (5, 10, 20)]
    cases += [("Local policy: 10%, $5k floor / $25k cap", bounded_reserve)]
    for label, target in cases:
        low, high, drag_low, drag_high = buffer_case(data, target)
        print(f"| {label} | ${low:,.2f}–${high:,.2f} | ${drag_low:,.2f}–${drag_high:,.2f} | ${low-drag_high:,.2f}–${high-drag_low:,.2f} |")
    print("\nConfirmed funding restored to withdrawal cash: " + "; ".join(f"{e['date']}: ${e['funding_restored_micros']/1e6:,.2f}" for e in data["episodes"]) + ". Even $50,000 would not cover either episode. Fixed reserves and NAV percentages must be capped at available assets.\n")

    shock = data["oct29_onyc"]
    daily = shock["proceeds_usdc"] * shock["adverse_spread"] / 365.25
    print("## Optional debt reduction\n")
    print(f"The five October 29 ONyc sales returned ${shock['proceeds_usdc']:,.2f} against ${shock['sold_mark_usdc']:,.2f} of adjacent oracle marks: ${shock['shortfall_usdc']:,.2f} shortfall. At an unchanged 3.02-point adverse spread, retaining that much debt costs about ${daily:,.2f}/day. The sale expense equals {shock['shortfall_usdc']/daily:.1f} days of that carry.\n")
    print(f"A one-day hold therefore avoids ${shock['shortfall_usdc']:,.2f} of **immediate** sale expense while adding approximately ${daily:,.2f} carry cost in this scenario. It retains market and liquidation exposure and can defer sale costs into a later withdrawal. This is not a claim of permanent net savings.\n")

    s = data["yield_scenario"]
    print("## Lower borrowing and real 1x\n")
    print("Synthetic $100,000 equity; 10% collateral APY; 7% normal or 13% shocked borrowing APY; 70 bps total entry-plus-exit cost on collateral. No fees or oracle/liquidity stress beyond the stated cost. Values include liquidation of the full position at the end of the holding period.\n")
    print("| Leverage | Normal, 3 days | Normal, 30 days | Normal, 180 days | Shock, 30 days | Price fall to 63% LTV brake |")
    print("|---|---:|---:|---:|---:|---:|")
    for level in (1, 1.5, 2, 2.5):
        values = [round_trip(s["equity_usdc"], level, s["native_apy"], s["normal_borrow_apy"], days, s["round_trip_bps"]) for days in (3, 30, 180)]
        stressed = round_trip(s["equity_usdc"], level, s["native_apy"], s["shock_borrow_apy"], 30, s["round_trip_bps"])
        brake = "No borrowing" if level == 1 else f"{(1-(1-1/level)/s['ltv_brake'])*100:.1f}%"
        print(f"| {level:g}x | " + " | ".join(f"${x:,.2f}" for x in [*values, stressed]) + f" | {brake} |")
    print("\nReal 1x removes borrowing exposure, not collateral price or exit-liquidity risk. The local Earn MAX change makes stored level 1 use the existing debt-zero transaction path after economic approval. Looping retains its 1.5x economic floor.\n")

    sales = data["nov4_sales"]
    actual = sales["sold_mark_usdc"] - sales["proceeds_usdc"]
    print("## Slower withdrawals, smaller sales and diversification\n")
    print(f"November 4 sold ${sales['sold_mark_usdc']:,.2f} of collateral for ${actual:,.2f} below its marks. **If** paced sales actually achieved 10–20 bps, the immediate expense would be ${sales['sold_mark_usdc']*.001:,.2f}–${sales['sold_mark_usdc']*.002:,.2f}, a conditional saving of ${actual-sales['sold_mark_usdc']*.002:,.2f}–${actual-sales['sold_mark_usdc']*.001:,.2f} before waiting costs. No historical quotes prove that fill was available.\n")
    print(f"In a fee-free toy pool, selling $5,000 once costs ${amm_sale(5000,1,False):.2f}; ten pieces without replenishment cost ${amm_sale(5000,10,False):.2f}; ten pieces with complete replenishment between them cost ${amm_sale(5000,10,True):.2f}. Real extra fees and waiting exposure can erase the improvement.\n")
    print("Diversification scenario: a 50% allocation cap bounds a loss confined to one lane at half the vault exposure; a correlated shock still hits all lanes. It does not prove lower aggregate execution cost. Compare executable exits across independent collateral, borrowing reserves and swap liquidity; two loops on the same collateral are not independent protection.\n")
    print("The local implementation selects a 10% reserve with a $5,000 floor and $25,000 cap, a seven-day economic horizon, and true economic 1x for Earn MAX. Cash is reserved from incoming funds; raising the target does not refill an empty buffer. These are candidate settings, not demonstrated optima. Nothing has been deployed. The existing withdrawal waiting period is 600 seconds; a longer wait, paced execution, withdrawal charges and concentration limits remain separate proposals in `docs/earn-max-loss-controls.md`.")


if __name__ == "__main__":
    main()
